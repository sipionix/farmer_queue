-- Farmer Queue schema. Run the complete file in Supabase SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Farmer',
  role text not null default 'farmer' check (role in ('farmer','staff')),
  created_at timestamptz not null default now()
);

create table if not exists public.slot_capacity (
  id bigint generated by default as identity primary key,
  booking_date date not null,
  centre text not null,
  slot_time text not null,
  capacity integer not null check (capacity between 1 and 100),
  unique (booking_date, centre, slot_time)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  token text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  farmer_name text not null,
  phone text not null,
  centre text not null,
  produce text not null,
  booking_date date not null,
  slot_time text not null,
  status text not null default 'booked' check (status in ('booked','inspecting','completed','cancelled','no-show')),
  created_at timestamptz not null default now()
);
create index if not exists bookings_user_created_idx on public.bookings(user_id, created_at desc);
create index if not exists bookings_slot_idx on public.bookings(booking_date, centre, slot_time);

-- SECURITY DEFINER helper avoids recursive RLS checks on profiles.
create or replace function public.is_staff(check_user uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=check_user and role='staff') $$;
grant execute on function public.is_staff(uuid) to authenticated;

alter table public.profiles enable row level security;
alter table public.slot_capacity enable row level security;
alter table public.bookings enable row level security;

drop policy if exists "Read own profile" on public.profiles;
create policy "Read own profile" on public.profiles for select to authenticated using (id = auth.uid() or public.is_staff(auth.uid()));
drop policy if exists "Insert own profile" on public.profiles;
create policy "Insert own profile" on public.profiles for insert to authenticated with check (id = auth.uid() and role='farmer');
drop policy if exists "Update own profile name" on public.profiles;
create policy "Update own profile name" on public.profiles for update to authenticated using (id=auth.uid()) with check (id=auth.uid() and role='farmer');

drop policy if exists "Authenticated read slot capacity" on public.slot_capacity;
create policy "Authenticated read slot capacity" on public.slot_capacity for select to authenticated using (true);
drop policy if exists "Staff manage slot capacity" on public.slot_capacity;
create policy "Staff manage slot capacity" on public.slot_capacity for all to authenticated using (public.is_staff(auth.uid())) with check (public.is_staff(auth.uid()));

drop policy if exists "Farmers read own bookings and staff all" on public.bookings;
create policy "Farmers read own bookings and staff all" on public.bookings for select to authenticated using (user_id=auth.uid() or public.is_staff(auth.uid()));
drop policy if exists "Staff update bookings" on public.bookings;
create policy "Staff update bookings" on public.bookings for update to authenticated using (public.is_staff(auth.uid())) with check (public.is_staff(auth.uid()));

-- Automatically create a farmer profile on signup.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  insert into public.profiles(id, full_name, role)
  values(new.id, coalesce(new.raw_user_meta_data->>'full_name','Farmer'), 'farmer')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Booking is transactional and serializes requests for the same centre/date/slot.
create or replace function public.create_booking(
  p_farmer_name text, p_phone text, p_centre text, p_produce text,
  p_booking_date date, p_slot_time text
) returns table(id uuid, token text, status text)
language plpgsql security definer set search_path=public
as $$
declare cap integer; used integer; new_id uuid; new_token text;
begin
  if auth.uid() is null then raise exception 'Please sign in first.'; end if;
  if p_booking_date < current_date then raise exception 'Choose today or a future date.'; end if;
  if length(trim(p_farmer_name)) < 2 or p_phone !~ '^[0-9]{10}$' then raise exception 'Enter a valid name and 10-digit mobile number.'; end if;
  -- Create the capacity row if this is the first request for the slot.
  insert into public.slot_capacity(booking_date,centre,slot_time,capacity)
  values(p_booking_date,p_centre,p_slot_time,
    case p_slot_time when '09:00–10:00' then 3 when '10:00–11:00' then 5
      when '11:00–12:00' then 2 when '12:00–13:00' then 4
      when '14:00–15:00' then 3 else 2 end)
  on conflict (booking_date,centre,slot_time) do nothing;
  select capacity into cap from public.slot_capacity
    where booking_date=p_booking_date and centre=p_centre and slot_time=p_slot_time for update;
  select count(*) into used from public.bookings
    where booking_date=p_booking_date and centre=p_centre and slot_time=p_slot_time
      and status not in ('cancelled','no-show');
  if used >= cap then raise exception 'This slot is full. Please choose another time.'; end if;
  new_token := 'FQ-' || upper(substr(encode(gen_random_bytes(6),'hex'),1,8));
  insert into public.bookings(user_id,farmer_name,phone,centre,produce,booking_date,slot_time,token)
  values(auth.uid(),trim(p_farmer_name),p_phone,p_centre,p_produce,p_booking_date,p_slot_time,new_token)
  returning bookings.id into new_id;
  return query select new_id,new_token,'booked'::text;
end;
$$;
revoke all on function public.create_booking(text,text,text,text,date,text) from public;
grant execute on function public.create_booking(text,text,text,text,date,text) to authenticated;

grant usage on schema public to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select on public.slot_capacity to authenticated;
grant select, update on public.bookings to authenticated;
